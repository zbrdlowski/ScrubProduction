CREATE TABLE IF NOT EXISTS accounting_tatra_bank_transactions (
  id bigint unsigned NOT NULL AUTO_INCREMENT,
  import_id bigint unsigned NOT NULL,
  source_key char(64) NOT NULL,
  transaction_date datetime NOT NULL,
  processing_date date NOT NULL,
  transaction_type varchar(16) NOT NULL,
  type_raw varchar(128) NOT NULL,
  own_account varchar(64) NOT NULL,
  counterparty_account varchar(64) DEFAULT NULL,
  counterparty_bank varchar(32) DEFAULT NULL,
  payer_name varchar(255) DEFAULT NULL,
  amount decimal(16,2) NOT NULL,
  currency varchar(3) NOT NULL,
  variable_symbol varchar(128) DEFAULT NULL,
  payer_reference varchar(255) DEFAULT NULL,
  bank_reference text DEFAULT NULL,
  payment_message text DEFAULT NULL,
  payout_reference varchar(128) DEFAULT NULL,
  matched_order_id bigint(20) DEFAULT NULL,
  matched_custom_order_id bigint DEFAULT NULL,
  export_order_number varchar(128) DEFAULT NULL,
  match_method varchar(32) NOT NULL DEFAULT 'UNMATCHED',
  manual_override tinyint NOT NULL DEFAULT 0,
  excluded tinyint NOT NULL DEFAULT 0,
  reviewed_by int DEFAULT NULL,
  reviewed_at datetime DEFAULT NULL,
  created_at datetime NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (id),
  UNIQUE KEY uq_tatra_bank_source_key (source_key),
  KEY ix_tatra_bank_date_type (transaction_date, transaction_type),
  KEY ix_tatra_bank_order (matched_order_id),
  KEY ix_tatra_bank_custom (matched_custom_order_id),
  CONSTRAINT fk_tatra_bank_import FOREIGN KEY (import_id) REFERENCES accounting_tatra_imports (id),
  CONSTRAINT fk_tatra_bank_order FOREIGN KEY (matched_order_id) REFERENCES orders (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
